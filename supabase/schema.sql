-- ---------------------------------------------------------------------------
-- ตาราง
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  role text not null default 'pending' check (role in ('admin', 'viewer', 'pending')),
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id text primary key,
  fb_id text unique,                 -- เลขโพสต์ที่อ่านได้จาก Comment ID
  fb_key text,                       -- รหัสจากลิงก์ที่ลงทะเบียน (pfbid / เลขโพสต์) ใช้จับคู่กับ CSV
  fb_url text check (fb_url is null or fb_url ~* '^https://([a-z0-9-]+\.)?(facebook\.com|fb\.com|fb\.watch|fb\.me)/'),
  url text,                          -- ลิงก์โพสต์ที่อ่านได้จาก CSV
  title text not null default 'โพสต์ใหม่',
  note text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid,
  first_imported timestamptz,
  last_imported timestamptz
);
create unique index if not exists posts_fb_key_uniq on public.posts(fb_key) where fb_key is not null and fb_key <> '';

create table if not exists public.comments (
  id text primary key,
  post_id text not null references public.posts(id) on update cascade,
  parent_id text,
  text text,
  ts timestamp,                      -- เวลาคอมเมนต์ (เวลาไทย)
  like_count int default 0,
  reply_count int default 0,
  url text,
  user_id text,
  user_name text,
  user_homepage text,
  imported_at timestamptz default now(),
  auto_label text,
  auto_category text,
  auto_urgency text,
  auto_location text,
  matched text,
  is_problem boolean not null default false,
  category text,
  urgency text,
  location text,
  review text not null default 'pending' check (review in ('pending', 'confirmed', 'rejected')),
  status text,
  note text,
  updated_at timestamptz,
  updated_by uuid
);
create index if not exists comments_post_idx on public.comments(post_id);
create index if not exists comments_ts_idx on public.comments(ts);

create table if not exists public.history (
  id bigint generated by default as identity primary key,
  comment_id text,
  at timestamptz not null default now(),
  user_id uuid,
  user_email text,
  field text,
  old_value text,
  new_value text
);
create index if not exists history_comment_idx on public.history(comment_id);

create table if not exists public.imports (
  id text primary key,
  at timestamptz not null default now(),
  filename text,
  post_id text,
  total int default 0,
  added int default 0,
  duplicate int default 0,
  user_id uuid,
  user_email text
);

create table if not exists public.keywords (
  grp text primary key,
  words text
);

-- ---------------------------------------------------------------------------
-- สิทธิ์ผู้ใช้
-- ---------------------------------------------------------------------------
create or replace function public.app_role() returns text
language sql stable security definer set search_path = public as $$
  select coalesce((select role from public.profiles where user_id = auth.uid()), 'anon')
$$;
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$ select public.app_role() = 'admin' $$;
create or replace function public.is_member() returns boolean
language sql stable security definer set search_path = public as $$ select public.app_role() in ('admin', 'viewer') $$;

-- สมัครใหม่ → สร้าง profile (คนแรกเป็นผู้ดูแล คนต่อไปรออนุมัติ)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(user_id, email, display_name, role)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email, '@', 1)),
          case when exists (select 1 from public.profiles where role = 'admin') then 'pending' else 'admin' end)
  on conflict (user_id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.set_user_role(p_user uuid, p_role text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'เฉพาะผู้ดูแล'; end if;
  if p_role not in ('admin', 'viewer', 'pending') then raise exception 'สิทธิ์ไม่ถูกต้อง'; end if;
  if p_role <> 'admin' and (select role from profiles where user_id = p_user) = 'admin'
     and (select count(*) from profiles where role = 'admin') <= 1 then
    raise exception 'ต้องมีผู้ดูแลอย่างน้อย 1 คน';
  end if;
  update profiles set role = p_role where user_id = p_user;
end $$;

