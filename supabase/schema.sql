-- ระบบสรุปคอมเมนต์แจ้งปัญหา — สำนักงานเขตทวีวัฒนา
-- วิธีใช้: Supabase → SQL Editor → วางไฟล์นี้ทั้งไฟล์ → Run (รันซ้ำได้ ไม่ลบข้อมูล)
--
-- ความปลอดภัย: หน้าเว็บเปิดได้ทุกคน แต่ข้อมูลทุกตารางเปิด Row Level Security
--   - ไม่ได้ล็อกอิน (anon)         : ไม่เห็นอะไรเลย
--   - สมัครแล้วแต่ยังไม่อนุมัติ (pending): ไม่เห็นอะไรเลย
--   - ผู้ดู (viewer)               : อ่านได้อย่างเดียว
--   - ผู้ดูแล (admin)              : อ่าน/เขียน/นำเข้า/จัดการผู้ใช้
--   คนแรกที่สมัครจะเป็นผู้ดูแลอัตโนมัติ
