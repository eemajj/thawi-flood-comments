# ถนนที่มักตามด้วยเลขซอย เช่น "ทวีวัฒนา 13", "พุทธมณฑลสาย 2 ซ.5"
SOI_ROADS = ["ทวีวัฒนา", "พุทธมณฑลสาย 2", "พุทธมณฑลสาย 3", "พุทธมณฑลสาย 4",
             "ศาลาธรรมสพน์", "ฉิมพลี", "บรมราชชนนี", "อุทยาน", "อักษะ",
             "สวนผัก", "กาญจนาภิเษก"]

THAI_DIGITS = str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789")
ZERO_WIDTH = re.compile(r"[​‌‍﻿]")


def split_words(raw):
    """แปลงข้อความ keyword (บรรทัดละคำ หรือคั่นด้วย ,) เป็นรายการ"""
    out = []
    for part in re.split(r"[\n,]", raw or ""):
        w = part.strip()
        if w and w not in out:
            out.append(w)
    return out


def normalize(text):
    t = ZERO_WIDTH.sub("", text or "")
    t = t.translate(THAI_DIGITS).lower()
    t = re.sub(r"\s+", " ", t)
    return t.strip()


def _match(words, text):
    return [w for w in words if normalize(w) in text]


def _road_pattern(road):
    # ให้ "พุทธมณฑลสาย 2" ตรงกับ "พุทธมณฑลสาย2" ด้วย
    return r"\s*".join(re.escape(ch) for ch in road.replace(" ", ""))


def extract_location(raw, places):
    """ดึงสถานที่ (ซอย/ชุมชน/หมู่บ้าน/ถนน/สถานที่ที่รู้จัก) จากข้อความ"""
    text = ZERO_WIDTH.sub("", raw or "").translate(THAI_DIGITS)
    found = []

    def add(s):
        s = re.sub(r"\s+", " ", s).strip(" .,-")
        if s and not any(s in f for f in found):
            found[:] = [f for f in found if f not in s]
            found.append(s)

    roads = sorted(set(SOI_ROADS) | {p for p in places if not p.startswith("คลอง")},
                   key=len, reverse=True)
    road_re = "|".join(_road_pattern(r) for r in roads) if roads else "(?!)"
    soi_mark = r"(?:ซอย|ชอย|ซ\s*\.|ซ(?=\s*\d))"

    # 1) ถนน + ซอย + เลข เช่น "ทวีวัฒนา ซ.9", "ทวีวัฒนา 13", "ซ.ทวีวัฒนา13", "ชอยทวีวัฒนา13"
    for m in re.finditer(
            rf"(?:{soi_mark}\s*)?({road_re})\s*(?:{soi_mark}\s*)?(\d{{1,3}}(?:\s*/\s*\d{{1,3}})?)(?!\d)",
            text):
        road = _canon_road(m.group(1), roads)
        if road.startswith("พุทธมณฑลสาย") and not re.search(soi_mark, m.group(0)):
            # "พุทธมณฑลสาย 2" เลขเป็นส่วนของชื่อถนน ไม่ใช่ซอย
            continue
        add(f"{road} ซ.{m.group(2).replace(' ', '')}")

    # 2) ซอย + เลข/ชื่อ ที่ไม่ได้ขึ้นต้นด้วยถนนที่รู้จัก
    # (ชื่อซอยต้องติดกับคำว่าซอย เพื่อไม่ให้ "ทั้งซอย มืดมาก" กลายเป็นชื่อซอย)
    for m in re.finditer(rf"{soi_mark}(?:\s*(\d{{1,3}}(?:/\d{{1,3}})?)|([ก-๙A-Za-z][ก-๙A-Za-z0-9]{{1,24}}))", text):
        val = m.group(1) or m.group(2)
        if re.match(road_re, val):
            continue
        val = re.split(r"(ท่วม|น้ำ|ริม|ด้าน|ตรง|หน้า|ตอนนี้|ค่ะ|ครับ|คะ|นะ)", val)[0]
        if val:
            add(f"ซ.{val}")

    # 3) ชุมชน / หมู่บ้าน / ถนน / แยก + ชื่อ
    for prefix, label in (("ชุมชน", "ชุมชน"), ("หมู่บ้าน", "หมู่บ้าน"), ("มบ\\.", "หมู่บ้าน"),
                          ("ถนน", "ถ."), ("ถ\\.", "ถ."), ("แยก", "แยก")):
        for m in re.finditer(rf"{prefix}\s*([ก-๙A-Za-z0-9][ก-๙A-Za-z0-9\-]{{1,30}})", text):
            val = re.split(r"(ท่วม|น้ำขัง|ริม|ด้าน|ตรง|ตอนนี้|ค่ะ|ครับ|คะ|นะ|มี|ไม่)", m.group(1))[0]
            if len(val) >= 2:
                add(f"{label}{val}")

    # 4) สถานที่ที่รู้จัก (คลอง ฯลฯ) ถ้ายังไม่ได้อะไรที่เฉพาะเจาะจงกว่า
    norm = normalize(text)
    for p in sorted(places, key=len, reverse=True):
        if normalize(p).replace(" ", "") in norm.replace(" ", "") and not any(
                p.replace(" ", "") in f.replace(" ", "") for f in found):
            add(p)
    return ", ".join(found[:3])


def _canon_road(matched, roads):
    flat = matched.replace(" ", "")
    for r in roads:
        if r.replace(" ", "") == flat:
            return r
    return matched


def classify(text, keywords=None):
    """คืนผลคัดกรองเป็น dict

    label: problem | not_problem | unmatched | needs_view
      - needs_view : ไม่มีข้อความ (อาจเป็นรูป/สติกเกอร์) ต้องเปิดดูเอง
      - problem    : แจ้งปัญหา/ขอความช่วยเหลือ
      - not_problem: ให้กำลังใจ/ขอบคุณ/คุยทั่วไป
      - unmatched  : ไม่เข้าเกณฑ์ใดเลย (ผู้ดูแลควรไล่ดู กันเรื่องหลุด)
    """
    kw = keywords or DEFAULT_KEYWORDS
    norm = normalize(text)
    result = {"label": "unmatched", "is_problem": 0, "category": "", "urgency": "",
              "location": "", "matched": ""}
    if not norm or not re.search(r"[ก-๙a-z0-9]", norm):
        result["label"] = "needs_view"
        return result

    scores = {}
    matched = []
    for key, _, _ in CATEGORIES:
        hits = _match(split_words(kw.get(f"cat:{key}", "")), norm)
        if hits:
            # คำยาวให้น้ำหนักมากกว่า (เฉพาะเจาะจงกว่า)
            scores[key] = sum(1 + len(h) / 10 for h in hits)
            matched += hits
    help_hits = _match(split_words(kw.get("help", "")), norm)
    praise_hits = _match(split_words(kw.get("praise", "")), norm)
    urgent_hits = _match(split_words(kw.get("urgent", "")), norm)
    request_hits = _match(split_words(kw.get("request", "")), norm)
    places = split_words(kw.get("place", ""))
    location = extract_location(text, places)

    # "ชุมชน" อย่างเดียวบ่งบอกสถานที่ ไม่ใช่เรื่องสวัสดิการ
    if set(scores) == {"welfare"} and all(h == "ชุมชน" for h in _match(
            split_words(kw.get("cat:welfare", "")), norm)):
        scores.pop("welfare")

    is_problem = bool(scores) or bool(help_hits) or bool(urgent_hits and not praise_hits)
    if not is_problem and location and not praise_hits and request_hits:
        is_problem = True

    matched += help_hits + urgent_hits
    result["matched"] = ", ".join(dict.fromkeys(matched))
    result["location"] = location

    if is_problem:
        result["label"] = "problem"
        result["is_problem"] = 1
        result["category"] = max(scores, key=scores.get) if scores else "other"
        if urgent_hits:
            result["urgency"] = "urgent"
        elif request_hits:
            result["urgency"] = "request"
        else:
            result["urgency"] = "normal"
    elif praise_hits:
        result["label"] = "not_problem"
    return result


